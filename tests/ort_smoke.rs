//! Guards the ONNX Runtime *linkage*, which nothing else in the suite exercises
//! (the other tests use fake embedders). If this fails with "Failed to load ONNX
//! Runtime dylib", `ort/load-dynamic` was re-enabled or no runtime is linked: on
//! Windows that can silently pick up an unrelated `C:\Windows\System32\onnxruntime.dll`.
//!
//! The model is embedded, so the test needs no files, network or model download.

#![cfg(not(target_arch = "wasm32"))]

use ort::{session::Session, value::Tensor};

/// Minimal ONNX model: `c = a + b` over `float[1, 3]` (ir_version 8, opset 13).
const ADD_MODEL: &[u8] = &[
    0x08, 0x08, 0x3a, 0x54, 0x0a, 0x0e, 0x0a, 0x01, 0x61, 0x0a, 0x01, 0x62, 0x12, 0x01, 0x63, 0x22,
    0x03, 0x41, 0x64, 0x64, 0x12, 0x03, 0x61, 0x64, 0x64, 0x5a, 0x13, 0x0a, 0x01, 0x61, 0x12, 0x0e,
    0x0a, 0x0c, 0x08, 0x01, 0x12, 0x08, 0x0a, 0x02, 0x08, 0x01, 0x0a, 0x02, 0x08, 0x03, 0x5a, 0x13,
    0x0a, 0x01, 0x62, 0x12, 0x0e, 0x0a, 0x0c, 0x08, 0x01, 0x12, 0x08, 0x0a, 0x02, 0x08, 0x01, 0x0a,
    0x02, 0x08, 0x03, 0x62, 0x13, 0x0a, 0x01, 0x63, 0x12, 0x0e, 0x0a, 0x0c, 0x08, 0x01, 0x12, 0x08,
    0x0a, 0x02, 0x08, 0x01, 0x0a, 0x02, 0x08, 0x03, 0x42, 0x04, 0x0a, 0x00, 0x10, 0x0d,
];

#[test]
fn onnx_runtime_is_linked_and_runs_inference() -> anyhow::Result<()> {
    let mut session = Session::builder()?.commit_from_memory(ADD_MODEL)?;

    let a = Tensor::from_array(([1usize, 3], vec![1.0_f32, 2.0, 3.0].into_boxed_slice()))?;
    let b = Tensor::from_array(([1usize, 3], vec![10.0_f32, 20.0, 30.0].into_boxed_slice()))?;
    let outputs = session.run(ort::inputs!["a" => a, "b" => b])?;
    let (_, values) = outputs[0].try_extract_tensor::<f32>()?;

    assert_eq!(values, [11.0, 22.0, 33.0]);
    Ok(())
}
